// Run with: npm run build-electron && electron tests/model_workflow.cjs
// Exercises the start screen, creation preferences, save/reopen, and standard export.
const { app, Menu } = require('electron');
const { mkdtempSync, rmSync, writeFileSync, readFileSync, existsSync } = require('node:fs');
const { tmpdir } = require('node:os');
const { join } = require('node:path');
const { pathToFileURL } = require('node:url');
const profile = mkdtempSync(join(tmpdir(), '3dbench-model-workflow-'));
process.argv.push('--userData', profile);
app.on('quit', () => rmSync(profile, { recursive: true, force: true }));
app.requestSingleInstanceLock = () => true;
let done = false;
app.on('browser-window-created', (_, win) => {
 win.webContents.on('did-finish-load', async () => {
  if (done) return; done = true;
  try {
   const rendererErrors = [];
   win.webContents.on('console-message', details => { if (details.message?.includes('native menu')) { rendererErrors.push(details.message); console.error(details.message); } });
   win.focus();
   const result = await win.webContents.executeJavaScript(`(async () => {
    const assert = (value, message) => { if (!value) throw Error(message); };
    const waitFor = async (test, message) => { for (let i=0; i<100; i++) { if(test()) return; await new Promise(r=>setTimeout(r,25)); } throw Error(message); };
    const tick = () => new Promise(resolve => Vue.nextTick(resolve));
    if (open_interface) open_interface.hide();
    const home = document.querySelector('#new_model_button');
    assert(home && home.offsetWidth > 0, 'New Model must be visible on launch');
    assert(!document.querySelector('#start_files [format="free"]'), 'Generic format chooser is redundant');
    assert(document.querySelector('#start_files .start_screen_right'), 'Recent projects must stay visible');
    assert(BarItems.new_model.keybind.key === 78 && (BarItems.new_model.keybind.ctrl || BarItems.new_model.keybind.meta), 'Missing New Model shortcut');
    assert(MenuBar.menus.file.structure.includes('new_model'), 'Missing direct File action');
    settings.new_project_dialog.value = true;
    home.click();
    await tick();
    assert(Project && Format.id === 'free', 'Home must create generic model directly');
    assert(open_interface && open_interface.id === 'project', 'Respect project settings preference');
    open_interface.setFormValues({name: 'Workflow test', texture_size: [64,64]});
    open_interface.close(open_interface.confirmIndex);
    assert(Project.name === 'Workflow test' && Project.texture_width === 64, 'Project setup did not apply');
    new Cube({name: 'Workflow cube', from: [0,0,0], to: [8,8,8]}).init();
    Canvas.updateAll();
    assert(Codecs.project.extension === 'bench', 'Default project extension must be bench');
    assert(Codec.getAllExtensions().includes('bench') && Codec.getAllExtensions().includes('bbmodel'), 'Missing native or legacy open support');
    const savePath = ${JSON.stringify(join(profile, 'workflow.bench'))};
    Codecs.project.write(Codecs.project.compile(), savePath);
    await waitFor(() => Project.save_path === savePath, 'Bench save did not finish');
    BarItems.save_project_incremental.trigger();
    await waitFor(() => Project.save_path.endsWith('workflow_1.bench'), 'Incremental bench save failed');
    const model = Codecs.project.compile();
    assert(JSON.parse(model).elements.length === 1, 'Editable save lost geometry');
    const original = Project;
    original.saved = true;
    Interface.tab_bar.openNewTab();
    await tick();
    assert(document.querySelector('#new_model_button').offsetWidth > 0, 'Returning home must keep New Model visible');
    settings.new_project_dialog.value = false;
    document.querySelector('#new_model_button').click();
    await tick();
    assert(Project !== original && Format.id === 'free', 'Second project was not created');
    assert(!open_interface, 'Disabled setup preference should enter editor immediately');
    assert(original.elements.length === 1, 'Creating another project changed existing geometry');
    Codecs.project.load(JSON.parse(model), {path: ''});
    assert(Cube.all.length === 1 && Cube.all[0].name === 'Workflow cube', 'Reopen lost geometry');
    const gltf = JSON.parse(await Codecs.gltf.compile({encoding:'ascii', scale:16, animations:false}));
    assert(gltf.asset.version === '2.0' && gltf.meshes.length > 0, 'Standard export missing model');
    Project.saved = true;
    Interface.tab_bar.openNewTab();
    await tick();
    const start = document.querySelector('#start_screen').__vue__;
    // Loader creation must run onStart exactly once.
    let starts = 0;
    const loader = new ModelLoader('workflow_test', {name:'Test loader', icon:'add', onStart:()=>starts++});
    start.confirmSetupScreen(loader);
    assert(starts === 1, 'Loader ran more than once');
    loader.delete();
    start.search_term = 'no-such-project';
    await tick();
    assert(document.querySelector('.start_recent_empty')?.textContent.includes('No recent projects match'), 'Missing search empty state');
    start.search_term = '';
    assert(!document.querySelector('.start_workflow_description, .start_workflow_hint'), 'Unnecessary descriptors remain');
    start.show_splash_screen = false;
    await tick();
    await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
    return {home:true, projectSetup:true, multipleProjects:true, saveReopen:true, gltf:true, loader:true, search:true};
   })()`);
   if (!existsSync(join(profile, 'workflow.bench')) || !existsSync(join(profile, 'workflow_1.bench'))) throw Error('Bench files missing');
   if (JSON.parse(readFileSync(join(profile, 'workflow.bench'), 'utf8')).elements.length !== 1) throw Error('Saved bench contents invalid');
   writeFileSync(join(profile, 'legacy.bbmodel'), readFileSync(join(profile, 'workflow.bench')));
   await win.webContents.executeJavaScript(`(async () => {
    loadModelFile({path: ${JSON.stringify(join(profile, 'legacy.bbmodel'))}, content: ${JSON.stringify(readFileSync(join(profile, 'workflow.bench'), 'utf8'))}});
   })()`);
   await win.webContents.executeJavaScript(`Codecs.project.write(Codecs.project.compile(), Project.save_path)`);
   for(let i=0; i<50 && !existsSync(join(profile,'legacy.bench')); i++) await new Promise(r=>setTimeout(r,25));
   if(!existsSync(join(profile,'legacy.bench'))) throw Error('Legacy project did not migrate to bench');
   if(process.platform === 'darwin') {
    await new Promise(r=>setTimeout(r,800));
    let menu = Menu.getApplicationMenu();
    const newModel = menu.getMenuItemById('file/new_model');
    if(!newModel) throw Error('Native File menu missing: '+ JSON.stringify(menu.items.map(item=>({label:item.label,ids:item.submenu?.items.map(i=>i.id)})))+' '+rendererErrors.join(' '));
    const before = await win.webContents.executeJavaScript('ModelProject.all.length');
    newModel.click(newModel, win);
    await new Promise(r=>setTimeout(r,150));
    const after = await win.webContents.executeJavaScript('ModelProject.all.length');
    if(after !== before+1) throw Error('Native New Model command did not create project');
    await new Promise(r=>setTimeout(r,600));
    menu = Menu.getApplicationMenu();
    if(!menu.getMenuItemById('file/export/export_gltf')) throw Error('Native export submenu missing');
    const projectSettings = menu.getMenuItemById('file/project_window');
    projectSettings.click(projectSettings, win);
    await new Promise(r=>setTimeout(r,150));
    const opened = await win.webContents.executeJavaScript('open_interface?.id');
    if(opened !== 'project') throw Error('Native Project Settings command failed');
    await new Promise(r=>setTimeout(r,600));
    menu = Menu.getApplicationMenu();
    if(menu.getMenuItemById('file/new_model').enabled) throw Error('Native New Model must be disabled while a modal is open');
    const edit = menu.items.find(item=>item.id === 'edit');
    if(!edit?.submenu.items.some(item=>item.role === 'paste')) throw Error('Native text editing roles missing in dialog');
    await win.webContents.executeJavaScript('open_interface.close(open_interface.cancelIndex); Project.saved=true; Interface.tab_bar.openNewTab()');
    const hidden = await win.webContents.executeJavaScript('getComputedStyle(document.querySelector("#menu_bar")).display === "none"');
    if(!hidden) throw Error('macOS ribbon was not hidden');
    result.nativeMenu = true;
   }
   if(rendererErrors.some(message=>message.includes('native menu'))) throw Error(rendererErrors.join('\n'));
   await new Promise(r=>setTimeout(r,400));
   if (process.env.MODEL_WORKFLOW_SCREENSHOT) writeFileSync(process.env.MODEL_WORKFLOW_SCREENSHOT, (await win.webContents.capturePage()).toPNG());
   await win.webContents.executeJavaScript(`(async () => {
    ModelProject.all.find(p=>p.elements.length).select();
    const panel = Panels.textures;
    panel.fold(false);
    await new Promise(r=>setTimeout(r,300));
    const height = panel.container.getBoundingClientRect().height;
    panel.fold(true);
    if (!panel.container.getAnimations().length) throw Error('Panel collapse must animate');
    await new Promise(r=>setTimeout(r,90));
    const intermediate = panel.container.getBoundingClientRect().height;
    if (intermediate >= height || intermediate <= panel.tab_bar.clientHeight + 2) throw Error('Missing intermediate collapse frame');
    panel.fold(false);
    await new Promise(r=>setTimeout(r,300));
    if (panel.container.classList.contains('bench_folding') || Math.abs(panel.container.getBoundingClientRect().height - height)>2) throw Error('Interrupted collapse did not restore layout');
   })()`);
   win.webContents.debugger.attach('1.3');
   await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', {features:[{name:'prefers-reduced-motion',value:'reduce'}]});
   await win.webContents.executeJavaScript(`Panels.textures.fold(true); if (Panels.textures.container.getAnimations().length) throw Error('Reduced motion must skip collapse animation'); Panels.textures.fold(false); undefined`);
   win.webContents.debugger.detach();
   console.log('MODEL_WORKFLOW_RESULT', JSON.stringify(result));
   app.exit(0);
  } catch (error) { console.error('MODEL_WORKFLOW_FAILURE', error); app.exit(1); }
 });
});
setTimeout(() => { console.error('MODEL_WORKFLOW_TIMEOUT'); app.exit(1); }, 30000);
import(pathToFileURL(join(__dirname, '../electron/main.js')).href);
