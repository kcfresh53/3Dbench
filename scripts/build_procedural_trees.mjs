import {build} from 'esbuild';
import {readFile, writeFile} from 'node:fs/promises';
const textures = {};
for (const [key, name] of Object.entries({bark: 'bark_willow.jpg', pineBark: 'pine_bark.jpg', leaf: 'broadleaf.png', needle: 'needles.png'})) {
	const bytes = await readFile(`plugins/procedural_trees/textures/${name}`);
	textures[key] = `data:image/${name.endsWith('.png') ? 'png' : 'jpeg'};base64,${bytes.toString('base64')}`;
}
await writeFile('plugins/procedural_trees/src/texture/bundled.ts', '// Generated by build:trees. CC0 Poly Haven derivatives; see textures/README.md.\nexport const BUNDLED_TEXTURES = ' + JSON.stringify(textures) + ';\n');
await build({
	entryPoints: ['plugins/procedural_trees/src/standalone.ts'],
	bundle: true,
	format: 'iife',
	target: 'es2020',
	outfile: 'plugins/procedural_trees.js',
	legalComments: 'none',
	banner: {js: '// Procedural Trees v2 for 3DBench. Offline generation. Plugin code: GPL-3.0-or-later; embedded texture images: CC0, Poly Haven.\n// Install via File > Plugins > Load Plugin from File.'},
});
