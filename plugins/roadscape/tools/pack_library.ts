import { readFileSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import type { PropMesh } from '../src/core/types';
import type { MaterialTile, RoadLibrary } from '../src/core/library_types';
import { optimizeLibraryProps } from '../src/core/optimize/library_optimizer';
import type { PropReport } from '../src/core/optimize/library_optimizer';

interface SourceLibrary {
	sourceVersion: string;
	sourceSha256: string;
	author: string;
	atlasSize: number;
	atlas: string;
	materials: Record<string, MaterialTile>;
	objects: Record<string, PropMesh>;
}

/**
 * Build step: optimises every prop of the source artwork once (see the optimiser for how) and packs
 * the result as a compressed module. The plugin ships a single model per prop.
 */
const [, , sourcePath, outModule, outReport] = process.argv;
const source: SourceLibrary = JSON.parse(readFileSync(sourcePath, 'utf8')) as SourceLibrary;
const optimized: { props: Record<string, PropMesh>; reports: PropReport[] } = optimizeLibraryProps(source.objects);
const library: RoadLibrary = {
	sourceVersion: source.sourceVersion,
	sourceSha256: source.sourceSha256,
	author: source.author,
	atlasSize: source.atlasSize,
	atlas: source.atlas,
	materials: source.materials,
	props: optimized.props,
};
const packed: string = gzipSync(Buffer.from(JSON.stringify(library)), { level: 9 }).toString('base64');
writeFileSync(
	outModule,
	`// Generated by npm run build:roadscape. Source artwork: Baptiste Mollicone and SLX.\n// Roadscape ${source.sourceVersion}; source SHA256 ${source.sourceSha256}.\n// Props are optimised from the source models at build time; see src/core/optimize.\nexport const packedLibrary: string = '${packed}';\n`,
);
writeFileSync(outReport, JSON.stringify(optimized.reports, null, '\t') + '\n');
for (const r of optimized.reports) console.log(`${r.name.padEnd(38)} ${String(r.trianglesBefore).padStart(5)} -> ${String(r.trianglesAfter).padStart(4)} triangles`);
console.log(`Packed ${(packed.length / 1e6).toFixed(2)} MB (base64)`);
