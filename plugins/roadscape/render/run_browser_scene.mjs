import {readFileSync, writeFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {build} from 'esbuild';
const require = createRequire(import.meta.url);
const {chromium} = require('playwright');
const noPhotos = {name: 'np', setup(b) {b.onResolve({filter: /\/bundled$/}, () => ({path: 'x', namespace: 'stub'})); b.onLoad({filter: /.*/, namespace: 'stub'}, () => ({contents: "export const BUNDLED_TEXTURES = {bark:'',pineBark:'',leaf:'',needle:''};", loader: 'js'}));}};
const out = await build({entryPoints: ['plugins/roadscape/render/browser_scene.ts'], bundle: true, format: 'iife', write: false, plugins: [noPhotos], logLevel: 'warning'});
const lib = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const props = JSON.parse(readFileSync('/tmp/roadscape_props.json', 'utf8'));
const library = {sourceVersion: lib.sourceVersion, sourceSha256: lib.sourceSha256, author: lib.author, atlasSize: lib.atlasSize, atlas: lib.atlas, materials: lib.materials, props};
const three = readFileSync('node_modules/three/build/three.min.js', 'utf8');
writeFileSync('/tmp/browser_scene.html', `<html><body style="margin:0"><canvas id=c></canvas><script>${three}</script><script>const LIBRARY=${JSON.stringify(library)};</script><script>${out.outputFiles[0].text}</script></body></html>`);
const browser = await chromium.launch({args: ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist']});
const page = await browser.newPage({viewport: {width: 1400, height: 700}});
page.on('console', (m) => console.log('console', m.text().slice(0, 300)));
page.on('pageerror', (e) => console.log('pageerror', e.message));
await page.goto('file:///tmp/browser_scene.html');
await page.waitForFunction('window.done===true', {timeout: 120000});
console.log(JSON.stringify(await page.evaluate('window.stats')));
await page.screenshot({path: process.argv[3]});
await browser.close();
