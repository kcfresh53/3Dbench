import type { PresetName, Species, TreeParams, Variant } from '../core/types';

/** Fields a preset controls. User-level settings are kept when switching preset. */
export type PresetLook = Omit<
	TreeParams,
	'seed' | 'separateFoliage' | 'lodCount' | 'spreadLods' | 'useCustomTextures' | 'useBundledTextures' | 'barkImage' | 'leafImage'
>;
export type UserSettings = Pick<
	TreeParams,
	'seed' | 'separateFoliage' | 'lodCount' | 'spreadLods' | 'useCustomTextures' | 'useBundledTextures' | 'barkImage' | 'leafImage'
>;

