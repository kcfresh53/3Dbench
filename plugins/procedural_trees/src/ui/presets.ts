export const USER_DEFAULTS: UserSettings = {
	seed: 1,
	separateFoliage: true,
	lodCount: 1,
	spreadLods: false,
	useCustomTextures: true,
	useBundledTextures: true,
	barkImage: '',
	leafImage: '',
};

export function presetParams(name: PresetName): TreeParams {
	return { ...PRESET_LOOKS[name], ...USER_DEFAULTS };
}

export function presetLabel(name: PresetName): string {
	const [species, variant] = name.split('_') as [Species, Variant];
	return `${SPECIES_LABELS[species]} · ${VARIANT_LABELS[variant]}`;
}

export const PRESET_NAMES: PresetName[] = Object.keys(PRESET_LOOKS) as PresetName[];
