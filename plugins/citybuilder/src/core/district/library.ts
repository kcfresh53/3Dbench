const BY_ID: Map<number, DistrictType> = new Map(DISTRICT_TYPES.map((d: DistrictType): [number, DistrictType] => [d.id, d]));

export function districtById(id: number): DistrictType | undefined {
	return BY_ID.get(id);
}

export function districtByKey(key: string): DistrictType | undefined {
	return DISTRICT_TYPES.find((d: DistrictType): boolean => d.key === key);
}

export function hexToRgb(hex: string): [number, number, number] {
	const n: number = parseInt(hex.replace('#', ''), 16);
	return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}
