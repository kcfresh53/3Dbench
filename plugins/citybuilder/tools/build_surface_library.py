"""
Builds src/texture/library_data.ts from the packed textures of the FlexiBuilding Blender file.

    python3 tools/build_surface_library.py FlexiBuilding.blend

Only a small, downsampled subset is kept: tileable brick and concrete maps, a weathering map and a set of lit room
interiors that windows show. Every image is stored as raw 8-bit channels, deflated and base64 encoded.
"""
import base64, io, mmap, re, sys, zlib
import numpy as np
from PIL import Image

src = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else 'src/texture/library_data.ts'
fh = open(src, 'rb')
m = mmap.mmap(fh.fileno(), 0, access=mmap.ACCESS_READ)
ims = [(mt.start(), mt.group(1).decode()) for mt in re.finditer(rb'IM([\w\-\. ]{3,60}\.png)\x00', m)]
starts = [mt.start() for mt in re.finditer(rb'\x89PNG\r\n\x1a\n', m)]
images = {}
for s in starts:
    name = [n for p, n in ims if p <= s][-1]
    e = m.find(b'IEND', s) + 8
    images[name] = Image.open(io.BytesIO(m[s:e]))

def gray(im):
    a = np.array(im, dtype=np.float64)
    if a.ndim == 3: a = a[..., 0]
    if im.mode == 'I;16': a = a / 256.0
    return a

def pack(entry_id, arrays, size=None):
    planes = []
    for a in arrays:
        im = Image.fromarray(np.clip(a, 0, 255).astype(np.uint8))
        if size: im = im.resize((size, size), Image.LANCZOS)
        planes.append(np.array(im))
    h, w = planes[0].shape
    raw = np.stack(planes, axis=-1).tobytes()
    return entry_id, w, h, len(planes), base64.b64encode(zlib.compress(raw, 9)).decode()

def rgb(im):
    return np.array(im.convert('RGBA'), dtype=np.float64)

entries = []
T = 256
b = rgb(images['Brick-Wall_Maps.png'])
entries.append(pack('brick_maps', [b[..., 0], b[..., 1], b[..., 2]], T))
n = rgb(images['Brick-Wall_Normal.png'])
entries.append(pack('brick_normal', [n[..., 0], n[..., 1]], T))
entries.append(pack('brick_rough', [gray(images['Brick-Wall_Roughness.png'])], T))
c = rgb(images['Concrete_2_BaseColor.png'])
entries.append(pack('concrete_base', [c[..., 0], c[..., 1], c[..., 2]], T))
n = rgb(images['Concrete_2_Normal.png'])
entries.append(pack('concrete_normal', [n[..., 0], n[..., 1]], T))
entries.append(pack('concrete_rough', [gray(images['Concrete_2_Roughness.png'])], T))
entries.append(pack('grunge', [gray(images['Grunge-map.png'])], T))

# Lit interiors: the back-wall card with furniture of each room, 6 per atlas, 160 px.
CARD = 160
def cards(name, col, cols, prefix):
    a = rgb(images[name])
    cell = a.shape[0] // cols
    for row in range(6):
        tile = a[row * cell:(row + 1) * cell, col * cell:(col + 1) * cell]
        entries.append(pack(f'{prefix}_{row}', [tile[..., 0], tile[..., 1], tile[..., 2]], CARD))
cards('Comercial-Lighted-Interiors.png', 3, 5, 'shop')
cards('Office-Lighted-Interiors.png', 4, 6, 'office')
cards('Residencial-Lighted-Interiors.png', 4, 6, 'home')

lines = ['// Generated by tools/build_surface_library.py from the FlexiBuilding textures. Do not edit.',
         "export interface PackedImage { w: number; h: number; c: number; z: string }",
         'export const SURFACE_DATA: Record<string, PackedImage> = {']
total = 0
for eid, w, h, ch, z in entries:
    lines.append(f"\t{eid}: {{ w: {w}, h: {h}, c: {ch}, z: '{z}' }},")
    total += len(z)
lines.append('};')
open(out, 'w').write('\n'.join(lines) + '\n')
print(len(entries), 'images,', total // 1024, 'KB base64')
